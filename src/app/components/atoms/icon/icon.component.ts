  'arrow-down' | 
  'arrow-up' | 
  'check' | 
  'close' | 
  'info' | 
  'warning' | 
  'success' | 
  'error' | 
  'user' | 
  'settings';

export type IconSize = 'sm' | 'md' | 'lg';

